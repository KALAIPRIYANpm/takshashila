-- School infrastructure: schools request furniture, fans, water, repairs; staff verify, approve and pay vendors.

-- Schools sign in like everyone else (phone + OTP) with their own role.
ALTER TABLE users DROP CONSTRAINT users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('student', 'school', 'field', 'manager', 'admin'));

CREATE TABLE schools (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id),
  name TEXT NOT NULL, udise_code TEXT NOT NULL UNIQUE,          -- 11-digit UDISE+ code identifies every school in India
  school_type TEXT NOT NULL, level TEXT NOT NULL, medium TEXT,
  headmaster TEXT NOT NULL, contact_role TEXT, email TEXT,
  address TEXT, village TEXT, district TEXT NOT NULL, state TEXT NOT NULL, pin TEXT,
  students INTEGER NOT NULL, girls INTEGER, teachers INTEGER NOT NULL, classrooms INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_schools_district ON schools (district);

CREATE SEQUENCE infra_code_seq START 1001;

CREATE TABLE infra_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE,
  school_id INTEGER NOT NULL REFERENCES schools(id),
  status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'verified', 'approved', 'ordered', 'delivered', 'rejected')),
  title TEXT NOT NULL, urgency TEXT NOT NULL CHECK (urgency IN ('critical', 'high', 'normal')),
  justification TEXT NOT NULL, beneficiaries INTEGER NOT NULL,
  estimate INTEGER NOT NULL, amount_sanctioned INTEGER,
  priority DOUBLE PRECISION NOT NULL, priority_detail JSONB NOT NULL,
  created_by INTEGER NOT NULL REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), delivered_at TIMESTAMPTZ);
CREATE INDEX idx_infra_status ON infra_requests (status);
CREATE INDEX idx_infra_school ON infra_requests (school_id);

CREATE TABLE infra_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES infra_requests(id) ON DELETE CASCADE,
  item_key TEXT NOT NULL, name TEXT NOT NULL, category TEXT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0), unit_cost INTEGER NOT NULL CHECK (unit_cost >= 0), note TEXT);
CREATE INDEX idx_infra_items_req ON infra_items (request_id);

-- Photos of the current condition, vendor quotations, delivery proof, invoices.
CREATE TABLE infra_documents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES infra_requests(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('condition', 'quotation', 'delivery', 'invoice')),
  file_name TEXT NOT NULL, stored_name TEXT NOT NULL, mime TEXT, size BIGINT,
  uploaded_by INTEGER REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_infra_docs_req ON infra_documents (request_id);

CREATE TABLE infra_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES infra_requests(id) ON DELETE CASCADE,
  actor_id INTEGER NOT NULL REFERENCES users(id),
  action TEXT NOT NULL, comment TEXT, amount INTEGER, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_infra_events_req ON infra_events (request_id);

-- Vendor payments for an approved infrastructure request go through the same maker-checker flow.
ALTER TABLE payments DROP CONSTRAINT payments_kind_check;
ALTER TABLE payments ADD CONSTRAINT payments_kind_check CHECK (kind IN ('scholarship', 'vendor', 'training', 'infrastructure'));
ALTER TABLE payments ADD COLUMN infra_request_id INTEGER REFERENCES infra_requests(id);
CREATE INDEX idx_payments_infra ON payments (infra_request_id);
