CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT, phone TEXT NOT NULL UNIQUE,
  role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'field', 'manager', 'admin')),
  district TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now());

CREATE TABLE otps (
  phone TEXT PRIMARY KEY, code_hash TEXT NOT NULL, expires_at BIGINT NOT NULL, tries INTEGER NOT NULL DEFAULT 0);

-- One row per OTP sent, for rate limits (per phone and per IP). Rows older than a day are pruned.
CREATE TABLE otp_sends (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, phone TEXT NOT NULL, ip TEXT, sent_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_otp_sends_phone ON otp_sends (phone, sent_at);
CREATE INDEX idx_otp_sends_ip ON otp_sends (ip, sent_at);

CREATE SEQUENCE application_code_seq START 4101;

CREATE TABLE applications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE,
  student_id INTEGER NOT NULL UNIQUE REFERENCES users(id), mobilizer_id INTEGER REFERENCES users(id),
  project TEXT NOT NULL DEFAULT 'Project Bharat',
  status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'field_verified', 'approved', 'disbursed', 'rejected')),
  aadhaar_hash TEXT NOT NULL UNIQUE, aadhaar_last4 TEXT NOT NULL, whatsapp TEXT, email TEXT,
  full_name TEXT NOT NULL, gender TEXT NOT NULL, dob TEXT NOT NULL, alt_phone TEXT, alt_phone_owner TEXT,
  address TEXT, village TEXT, district TEXT NOT NULL, state TEXT NOT NULL, pin TEXT, languages TEXT, religion TEXT,
  level TEXT NOT NULL, institution TEXT NOT NULL, institution_type TEXT, course TEXT NOT NULL, study_year TEXT,
  last_percentage DOUBLE PRECISION NOT NULL, annual_fee INTEGER NOT NULL, fee_paid INTEGER DEFAULT 0, distance_km DOUBLE PRECISION, career_goal TEXT,
  answers JSONB NOT NULL, need_score DOUBLE PRECISION NOT NULL, merit_score DOUBLE PRECISION NOT NULL, final_score DOUBLE PRECISION NOT NULL,
  support_types TEXT NOT NULL, amount_requested INTEGER NOT NULL, amount_sanctioned INTEGER,
  story TEXT NOT NULL, other_benefits TEXT, visit_lat DOUBLE PRECISION, visit_lng DOUBLE PRECISION,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_app_status ON applications (status);
CREATE INDEX idx_app_district ON applications (district);
CREATE INDEX idx_app_mobilizer ON applications (mobilizer_id);

CREATE TABLE documents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INTEGER NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  doc_type TEXT NOT NULL, file_name TEXT NOT NULL, stored_name TEXT NOT NULL, mime TEXT, size BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_documents_app ON documents (application_id, doc_type);

CREATE TABLE reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INTEGER NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  actor_id INTEGER NOT NULL REFERENCES users(id),
  action TEXT NOT NULL, comment TEXT, amount INTEGER, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_reviews_app ON reviews (application_id);

CREATE TABLE payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, application_id INTEGER REFERENCES applications(id),
  kind TEXT NOT NULL CHECK (kind IN ('scholarship', 'vendor', 'training')),
  payee TEXT NOT NULL, payee_account TEXT, amount INTEGER NOT NULL CHECK (amount > 0), purpose TEXT,
  status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested', 'approved', 'paid', 'rejected')), utr TEXT,
  requested_by INTEGER NOT NULL REFERENCES users(id), approved_by INTEGER REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), paid_at TIMESTAMPTZ);
CREATE INDEX idx_payments_app ON payments (application_id);
CREATE INDEX idx_payments_status ON payments (status);

CREATE TABLE renewals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INTEGER NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  semester TEXT NOT NULL, marks DOUBLE PRECISION NOT NULL, attendance DOUBLE PRECISION NOT NULL,
  receipt_doc_id INTEGER REFERENCES documents(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'pending', note TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_renewals_app ON renewals (application_id);

CREATE TABLE trainings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL, kind TEXT NOT NULL, venue TEXT NOT NULL, location TEXT,
  held_on DATE NOT NULL, budget INTEGER DEFAULT 0, trainer TEXT, created_by INTEGER REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now());

CREATE TABLE attendance (
  training_id INTEGER NOT NULL REFERENCES trainings(id) ON DELETE CASCADE,
  application_id INTEGER NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  present INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (training_id, application_id));

CREATE TABLE opportunities (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company TEXT NOT NULL, title TEXT NOT NULL, kind TEXT NOT NULL,
  location TEXT, for_levels TEXT, stipend TEXT, deadline DATE, link TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now());

CREATE TABLE audit_log (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, actor_id INTEGER, action TEXT NOT NULL, entity TEXT NOT NULL,
  entity_id INTEGER, detail JSONB, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_audit_entity ON audit_log (entity, entity_id);
