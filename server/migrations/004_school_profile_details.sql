-- Fuller school profile (UDISE+-style): enrolment by gender, staff, location with geo-tag, facilities, photos.
-- `students` and `teachers` stay as stored totals (boys + girls, male + female teachers) so scoring keeps working.

ALTER TABLE schools
  ADD COLUMN boys INTEGER,
  ADD COLUMN cwsn INTEGER,                         -- children with special needs
  ADD COLUMN male_teachers INTEGER,
  ADD COLUMN female_teachers INTEGER,
  ADD COLUMN non_teaching INTEGER,
  ADD COLUMN established INTEGER,
  ADD COLUMN board TEXT,
  ADD COLUMN shifts TEXT,
  ADD COLUMN headmaster_phone TEXT,
  ADD COLUMN area_type TEXT,                       -- Rural / Urban
  ADD COLUMN taluk TEXT,                           -- block
  ADD COLUMN gram_panchayat TEXT,
  ADD COLUMN area_tags TEXT,                       -- comma-separated: Tribal area, Hilly / remote, …
  ADD COLUMN latitude DOUBLE PRECISION,
  ADD COLUMN longitude DOUBLE PRECISION,
  ADD COLUMN location_accuracy DOUBLE PRECISION,   -- metres, as reported by the phone
  ADD COLUMN located_at TIMESTAMPTZ,
  ADD COLUMN facilities JSONB NOT NULL DEFAULT '{}';

-- Photos of the school itself (not of one request). Each keeps where it was taken, when the phone shared it.
CREATE TABLE school_photos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id INTEGER NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('front', 'classroom', 'toilet', 'water', 'kitchen', 'playground', 'other')),
  file_name TEXT NOT NULL, stored_name TEXT NOT NULL, mime TEXT, size BIGINT,
  latitude DOUBLE PRECISION, longitude DOUBLE PRECISION, accuracy DOUBLE PRECISION,
  uploaded_by INTEGER REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX idx_school_photos_school ON school_photos (school_id);
CREATE INDEX idx_schools_taluk ON schools (district, taluk);
